package org.eclipse.neoscada.protocol.iec60870.tls;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.PrivateKey;
import java.security.cert.CertificateException;
import java.security.cert.CertificateFactory;
import java.security.cert.X509Certificate;
import java.security.spec.PKCS8EncodedKeySpec;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Base64;
import java.util.HexFormat;
import java.util.List;
import javax.crypto.Cipher;
import javax.crypto.EncryptedPrivateKeyInfo;
import javax.crypto.SecretKeyFactory;
import javax.crypto.spec.PBEKeySpec;

/**
 * Certificates and private keys read from PEM files.
 *
 * <p>
 * Utilities and integrators hand out certificates and keys as PEM files. The JDK reads certificates itself but
 * accepts a private key only as PKCS#8, so the two older encodings OpenSSL still writes — PKCS#1 for RSA and SEC1
 * for EC — are converted here rather than rejected. A cryptography library would be a heavy dependency for this
 * one need.
 *
 * <p>
 * Every accepted form is one OpenSSL writes without being asked for anything unusual, so a key
 * generated by the commands in the documentation loads whichever of them it happens to be in.
 */
public final class Pem {

  /** The DER for the AlgorithmIdentifier field naming RSA, whose parameters are always absent. */
  private static final byte[] RSA_ALGORITHM = HexFormat.of().parseHex("300D06092A864886F70D0101010500");

  /** The object identifier for an elliptic-curve public key, which the curve name follows. */
  private static final byte[] EC_PUBLIC_KEY_OID = HexFormat.of().parseHex("06072A8648CE3D0201");

  private Pem() {
  }

  /**
   * Every certificate in a file, in the order written.
   *
   * <p>
   * A chain file holds the certificate first and the authorities that signed it after, which is the
   * order both a key manager and a trust manager want.
   *
   * @throws IOException if the file cannot be read or holds no certificate
   */
  public static List<X509Certificate> readCertificates(final Path file) throws IOException {
    final byte[] contents = Files.readAllBytes(file);
    final List<X509Certificate> certificates = new ArrayList<>();

    try {
      // The factory reads PEM directly, and reads a whole chain when given the whole file.
      final CertificateFactory factory = CertificateFactory.getInstance("X.509");
      final ByteArrayInputStream pem = new ByteArrayInputStream(contents);

      for (final java.security.cert.Certificate certificate : factory.generateCertificates(pem)) {
        certificates.add((X509Certificate) certificate);
      }
    } catch (final CertificateException ex) {
      throw new IOException("Not a readable certificate file: " + file + " (" + ex.getMessage() + ")", ex);
    }

    if (certificates.isEmpty()) {
      throw new IOException("No certificate in " + file);
    }
    return certificates;
  }

  /**
   * The private key in a file, in any of the encodings OpenSSL writes.
   *
   * @param password the password an encrypted key was written with, or null for an unencrypted one
   * @throws IOException if the file holds no key, or holds one that cannot be decoded
   */
  public static PrivateKey readPrivateKey(final Path file, final char[] password) throws IOException {
    final String text = Files.readString(file, StandardCharsets.ISO_8859_1);

    final byte[] pkcs8 = Pem.decode(text, "PRIVATE KEY");
    if (pkcs8 != null) {
      return Pem.toPrivateKey(pkcs8, file);
    }

    final byte[] rsa = Pem.decode(text, "RSA PRIVATE KEY");
    if (rsa != null) {
      return Pem.toPrivateKey(Pem.wrapPkcs1(rsa), file);
    }

    final byte[] ec = Pem.decode(text, "EC PRIVATE KEY");
    if (ec != null) {
      return Pem.toPrivateKey(Pem.wrapSec1(ec, file), file);
    }

    final byte[] encrypted = Pem.decode(text, "ENCRYPTED PRIVATE KEY");
    if (encrypted != null) {
      if (password == null) {
        throw new IOException("The private key in " + file + " is encrypted, but no password was configured");
      }
      return Pem.toPrivateKey(Pem.decrypt(encrypted, password, file), file);
    }

    throw new IOException("No private key in " + file);
  }

  /** The DER inside the first {@code -----BEGIN <label>-----} block, or null if there is none. */
  private static byte[] decode(final String text, final String label) throws IOException {
    final String begin = "-----BEGIN " + label + "-----";
    final String end = "-----END " + label + "-----";

    final int start = text.indexOf(begin);
    if (start < 0) {
      return null;
    }
    final int finish = text.indexOf(end, start);
    if (finish < 0) {
      throw new IOException("A " + begin + " block is never closed");
    }

    final String body = text.substring(start + begin.length(), finish);
    try {
      return Base64.getMimeDecoder().decode(body);
    } catch (final IllegalArgumentException ex) {
      throw new IOException("The " + label + " block is not valid base 64", ex);
    }
  }

  /** A PKCS#8 key of whatever algorithm it names, which the encoding itself carries. */
  private static PrivateKey toPrivateKey(final byte[] pkcs8, final Path file) throws IOException {
    final PKCS8EncodedKeySpec spec = new PKCS8EncodedKeySpec(pkcs8);

    // The algorithm is inside the key, but KeyFactory has to be asked for one by name, so the
    // algorithms a TLS certificate can use are tried in turn.
    for (final String algorithm : new String[] { "RSA", "EC", "DSA", "Ed25519" }) {
      try {
        return KeyFactory.getInstance(algorithm).generatePrivate(spec);
      } catch (final GeneralSecurityException ignored) {
        // Not this algorithm; the last one to fail decides the message below.
      }
    }

    throw new IOException("The private key in " + file + " is not RSA, EC, DSA or Ed25519");
  }

  /** A bare PKCS#1 RSA key becomes PKCS#8 by naming its algorithm around it. */
  private static byte[] wrapPkcs1(final byte[] pkcs1) {
    return Pem.sequence(
        new byte[] { 0x02, 0x01, 0x00 }, // version 0
        Pem.RSA_ALGORITHM, Pem.tag(0x04, pkcs1)
    );
  }

  /**
   * A SEC1 elliptic-curve key becomes PKCS#8 the same way, but its curve has to move.
   *
   * <p>
   * SEC1 carries the curve inside the key; PKCS#8 carries it outside, beside the algorithm, and
   * RFC 5915 says not to carry it in both. So the field is lifted out of the key and put where
   * PKCS#8 wants it, leaving the rest untouched. Leaving it in place as well produces a key that
   * loads and works, and whose encoding does not match the one OpenSSL writes for the same key --
   * a difference that shows up only when something compares the two.
   *
   * <p>
   * The curve identifier is copied without being interpreted, so a curve this code has never heard
   * of still converts.
   */
  private static byte[] wrapSec1(final byte[] sec1, final Path file) throws IOException {
    final int[] cursor = { 0 };
    final byte[] body = Pem.contentsOf(sec1, cursor, 0x30);

    byte[] curve = null;
    final List<byte[]> kept = new ArrayList<>();

    final int[] field = { 0 };
    while (field[0] < body.length) {
      final int start = field[0];
      final int tag = body[start] & 0xFF;
      final byte[] contents = Pem.contentsOf(body, field, tag);

      if (tag == 0xA0) {
        curve = contents;
      } else {
        kept.add(Arrays.copyOfRange(body, start, field[0]));
      }
    }

    if (curve == null) {
      throw new IOException("The EC private key in " + file + " does not name its curve");
    }

    return Pem.sequence(
        new byte[] { 0x02, 0x01, 0x00 }, Pem.sequence(Pem.EC_PUBLIC_KEY_OID, curve),
        Pem.tag(0x04, Pem.sequence(kept.toArray(new byte[0][])))
    );
  }

  /**
   * Reads one tag-length-value at {@code cursor} and returns its contents, leaving the cursor after
   * it.
   */
  private static byte[] contentsOf(final byte[] der, final int[] cursor, final int expectedTag) throws IOException {
    int at = cursor[0];
    if (at + 2 > der.length) {
      throw new IOException("Truncated key structure");
    }
    if ((der[at] & 0xFF) != expectedTag) {
      throw new IOException("Unexpected field in key structure");
    }
    ++at;

    int length = der[at++] & 0xFF;
    if (length > 0x80) {
      // A long form: the low bits say how many octets of length follow.
      final int octets = length & 0x7F;
      if (octets > 4 || at + octets > der.length) {
        throw new IOException("Unreadable length in key structure");
      }
      length = 0;
      for (int index = 0; index < octets; ++index) {
        length = (length << 8) | (der[at++] & 0xFF);
      }
    } else if (length == 0x80) {
      throw new IOException("Key structure uses an indefinite length");
    }

    if (length < 0 || at + length > der.length) {
      throw new IOException("Truncated key structure");
    }

    cursor[0] = at + length;
    return Arrays.copyOfRange(der, at, at + length);
  }

  /** The PKCS#8 key inside an encrypted one, which carries the cipher it was written with. */
  private static byte[] decrypt(final byte[] encrypted, final char[] password, final Path file) throws IOException {
    try {
      final EncryptedPrivateKeyInfo info = new EncryptedPrivateKeyInfo(encrypted);
      final Cipher cipher = Cipher.getInstance(info.getAlgName());
      cipher.init(
          Cipher.DECRYPT_MODE, SecretKeyFactory.getInstance(info.getAlgName()).generateSecret(new PBEKeySpec(password)),
          info.getAlgParameters()
      );
      return info.getKeySpec(cipher).getEncoded();
    } catch (final GeneralSecurityException ex) {
      // A wrong password and a cipher the JDK does not have look the same from here, so say both.
      throw new IOException(
          "Unable to decrypt the private key in " + file + ": wrong password, or an unsupported cipher ("
              + ex.getMessage() + ")",
          ex
      );
    }
  }

  /** A SEQUENCE around the given already-encoded fields. */
  private static byte[] sequence(final byte[]... fields) {
    int length = 0;
    for (final byte[] field : fields) {
      length += field.length;
    }

    final byte[] contents = new byte[length];
    int at = 0;
    for (final byte[] field : fields) {
      System.arraycopy(field, 0, contents, at, field.length);
      at += field.length;
    }
    return Pem.tag(0x30, contents);
  }

  /** One tag-length-value around the given contents. */
  private static byte[] tag(final int tag, final byte[] contents) {
    final byte[] length = Pem.lengthOf(contents.length);
    final byte[] encoded = new byte[1 + length.length + contents.length];
    encoded[0] = (byte) tag;
    System.arraycopy(length, 0, encoded, 1, length.length);
    System.arraycopy(contents, 0, encoded, 1 + length.length, contents.length);
    return encoded;
  }

  /** A length, short form below 128 and long form above it. */
  private static byte[] lengthOf(final int length) {
    if (length < 0x80) {
      return new byte[] { (byte) length };
    }

    int octets = 0;
    for (int remaining = length; remaining != 0; remaining >>>= 8) {
      ++octets;
    }

    final byte[] encoded = new byte[1 + octets];
    encoded[0] = (byte) (0x80 | octets);
    for (int index = octets; index > 0; --index) {
      encoded[index] = (byte) (length >>> (8 * (octets - index)));
    }
    return encoded;
  }

}
